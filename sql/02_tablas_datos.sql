-- Ejecutar conectado a bd_laboratorio_orm, no a postgres.
CREATE SCHEMA IF NOT EXISTS inventario;

-- Tipos de equipo
CREATE TABLE IF NOT EXISTS inventario.tipo_equipo (
    id_tipo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT
);

-- Equipos y su relacion con un tipo
CREATE TABLE IF NOT EXISTS inventario.equipo (
    id_equipo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    marca VARCHAR(100),
    estado VARCHAR(30) NOT NULL,
    cantidad INTEGER NOT NULL,
    id_tipo INTEGER NOT NULL,
    CONSTRAINT fk_equipo_tipo FOREIGN KEY (id_tipo)
        REFERENCES inventario.tipo_equipo(id_tipo),
    CONSTRAINT chk_equipo_cantidad CHECK (cantidad >= 0),
    CONSTRAINT chk_equipo_estado CHECK
        (estado IN ('Disponible', 'En mantenimiento', 'Fuera de servicio'))
);

